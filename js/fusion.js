    function initChassis(cv) {
        const ctx = cv.getContext('2d');
        // Build the frame: two side rails with cross members and a roll cage
        const L = 3.2, W = 1.3, H = 0.9;
        const P = [], E = [];
        const add = (x, y, z) => (P.push([x, y, z]), P.length - 1);
        const line = (a, b, kind) => E.push([a, b, kind || 0]);
        const xs = [-L / 2, -L / 4, 0, L / 4, L / 2];
        const low = [], lowR = [], up = [], upR = [];
        xs.forEach(x => { low.push(add(x, 0, -W / 2)); lowR.push(add(x, 0, W / 2)); });
        [-L / 4, 0, L / 4].forEach(x => { up.push(add(x, H, -W / 2 + 0.1)); upR.push(add(x, H, W / 2 - 0.1)); });
        for (let i = 0; i < xs.length - 1; i++) { line(low[i], low[i + 1]); line(lowR[i], lowR[i + 1]); }
        for (let i = 0; i < xs.length; i++) line(low[i], lowR[i]);
        for (let i = 0; i < 4; i++) { line(low[i], lowR[i + 1], 1); }
        for (let i = 0; i < 3; i++) { line(up[i], upR[i]); line(low[i + 1], up[i]); line(lowR[i + 1], upR[i]); }
        for (let i = 0; i < 2; i++) { line(up[i], up[i + 1]); line(upR[i], upR[i + 1]); }
        line(low[0], up[0], 1); line(lowR[0], upR[0], 1); line(low[4], up[2], 1); line(lowR[4], upR[2], 1);
        // wheels (circles approximated by polygons)
        const wheels = [[-L / 2 + 0.35, -W / 2 - 0.12], [-L / 2 + 0.35, W / 2 + 0.12], [L / 2 - 0.35, -W / 2 - 0.12], [L / 2 - 0.35, W / 2 + 0.12]];
        wheels.forEach(([wx, wz]) => {
            const ids = [];
            for (let k = 0; k < 18; k++) { const a = k / 18 * Math.PI * 2; ids.push(add(wx + Math.cos(a) * 0.32, Math.sin(a) * 0.32, wz)); }
            ids.forEach((id, k) => line(id, ids[(k + 1) % ids.length], 2));
        });
        // battery pack box under the floor
        const bx = [-0.7, 0.7], bz = [-0.45, 0.45], by = [-0.12, 0.05];
        const bp = {};
        bx.forEach(x => by.forEach(y => bz.forEach(z => bp[`${x},${y},${z}`] = add(x, y, z))));
        const k = (x, y, z) => bp[`${x},${y},${z}`];
        bx.forEach(x => by.forEach(y => line(k(x, y, bz[0]), k(x, y, bz[1]), 3)));
        bx.forEach(x => bz.forEach(z => line(k(x, by[0], z), k(x, by[1], z), 3)));
        by.forEach(y => bz.forEach(z => line(k(bx[0], y, z), k(bx[1], y, z), 3)));

        let rotY = -0.7, rotX = 0.42, drag = null, auto = true;
        const colors = ['#3d6fa8', '#8aa4c2', '#2b2d30', '#f37a20'];

        function resize() {
            const r = cv.getBoundingClientRect(), d = window.devicePixelRatio || 1;
            cv.width = r.width * d; cv.height = r.height * d; ctx.setTransform(d, 0, 0, d, 0, 0);
        }
        function draw() {
            const w = cv.clientWidth, h = cv.clientHeight;
            ctx.clearRect(0, 0, w, h);
            const s = Math.min(w, h) * 0.24, cx = w / 2, cy = h / 2 + 30;
            const cyR = Math.cos(rotY), syR = Math.sin(rotY), cxR = Math.cos(rotX), sxR = Math.sin(rotX);
            const proj = P.map(([x, y, z]) => {
                const x1 = x * cyR - z * syR, z1 = x * syR + z * cyR;
                const y1 = y * cxR - z1 * sxR, z2 = y * sxR + z1 * cxR;
                const f = 6 / (6 + z2);
                return [cx + x1 * s * f, cy - y1 * s * f, z2];
            });
            // ground grid
            ctx.strokeStyle = 'rgba(60,80,100,.12)'; ctx.lineWidth = 1;
            for (let g = -3; g <= 3; g++) {
                [[[g * 0.6, -0.35, -1.8], [g * 0.6, -0.35, 1.8]], [[-1.8, -0.35, g * 0.6], [1.8, -0.35, g * 0.6]]].forEach(([a, b]) => {
                    const pa = [a, b].map(([x, y, z]) => { const x1 = x * cyR - z * syR, z1 = x * syR + z * cyR; const y1 = y * cxR - z1 * sxR, z2 = y * sxR + z1 * cxR; const f = 6 / (6 + z2); return [cx + x1 * s * f, cy - y1 * s * f]; });
                    ctx.beginPath(); ctx.moveTo(pa[0][0], pa[0][1]); ctx.lineTo(pa[1][0], pa[1][1]); ctx.stroke();
                });
            }
            E.slice().sort((a, b) => (proj[b[0]][2] + proj[b[1]][2]) - (proj[a[0]][2] + proj[a[1]][2])).forEach(([a, b, kind]) => {
                ctx.strokeStyle = colors[kind]; ctx.lineWidth = kind === 1 ? 1.2 : kind === 2 ? 1.4 : 2.2;
                ctx.beginPath(); ctx.moveTo(proj[a][0], proj[a][1]); ctx.lineTo(proj[b][0], proj[b][1]); ctx.stroke();
            });
            // nodes
            ctx.fillStyle = '#fff'; ctx.strokeStyle = '#3d6fa8'; ctx.lineWidth = 1.2;
            [...low, ...lowR, ...up, ...upR].forEach(i => { ctx.beginPath(); ctx.arc(proj[i][0], proj[i][1], 2.4, 0, Math.PI * 2); ctx.fill(); ctx.stroke(); });
        }
        function loop() { if (auto && !drag) rotY += 0.004; draw(); requestAnimationFrame(loop); }
        cv.addEventListener('pointerdown', e => { drag = [e.clientX, e.clientY]; auto = false; cv.setPointerCapture(e.pointerId); });
        cv.addEventListener('pointermove', e => {
            if (!drag) return;
            rotY += (e.clientX - drag[0]) * 0.01;
            rotX = Math.max(-0.2, Math.min(1.3, rotX + (e.clientY - drag[1]) * 0.01));
            drag = [e.clientX, e.clientY];
        });
        cv.addEventListener('pointerup', () => { drag = null; setTimeout(() => auto = true, 2500); });
        window.addEventListener('resize', resize);
        resize();
        if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) { auto = false; draw(); } else loop();
    }
